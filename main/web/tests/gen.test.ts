// @vitest-environment jsdom
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { readNsd } from '../src/core/io';
import { generateCode, LANGUAGES, type LangId } from '../src/core/gen/generators';
import { classifyLine, forInfo, parseSignature } from '../src/core/lang/analyze';
import { translateExpr } from '../src/core/gen/expr';
import { DEFAULT_KEYWORDS, createDiagram, createElement, insertAt } from '../src/core/model';
import type { For } from '../src/core/model';

const fixture = (name: string) => readNsd(readFileSync(resolve(process.cwd(), 'tests/fixtures', name), 'utf8')).diagram;
const ex = (e: string, lang: LangId) => translateExpr(e, { lang, imports: new Set() });

describe('analysis', () => {
  it('classifies instruction lines', () => {
    const k = DEFAULT_KEYWORDS;
    expect(classifyLine('INPUT "Name: ", n', k)).toEqual({ t: 'input', prompt: '"Name: "', targets: ['n'] });
    expect(classifyLine('OUTPUT "x = ", x', k)).toEqual({ t: 'output', exprs: ['"x = "', 'x'] });
    expect(classifyLine('x <- 5', k)).toMatchObject({ t: 'assign', target: 'x', expr: '5' });
    expect(classifyLine('var n: int <- 3', k)).toMatchObject({ t: 'assign', target: 'n', decl: { base: 'int' } });
    expect(classifyLine('int i <- 0', k)).toMatchObject({ t: 'assign', target: 'i', decl: { base: 'int' } });
    expect(classifyLine('var a, b: double', k)).toMatchObject({ t: 'decl', names: ['a', 'b'] });
    expect(classifyLine('return x + 1', k)).toEqual({ t: 'return', expr: 'x + 1' });
    expect(classifyLine('leave 2', k)).toEqual({ t: 'leave', levels: 2 });
    expect(classifyLine('forward(100)', k)).toEqual({ t: 'call', expr: 'forward(100)' });
  });

  it('parses subroutine headers in Pascal, C and BASIC style', () => {
    const d = createDiagram('sub');
    expect(parseSignature({ ...d, text: ['fact(n: int): int'] })).toMatchObject({ name: 'fact', params: [{ name: 'n', type: { base: 'int' } }], result: { base: 'int' }, isFunction: true });
    expect(parseSignature({ ...d, text: ['double area(double r, int k)'] })).toMatchObject({ name: 'area', params: [{ name: 'r' }, { name: 'k' }], result: { base: 'double' } });
    expect(parseSignature({ ...d, text: ['f(a as Integer, b as Double) as Double'] })).toMatchObject({ name: 'f', params: [{ name: 'a' }, { name: 'b' }] });
    expect(parseSignature({ ...d, text: ['void show(int x)'] }).isFunction).toBe(false);
    expect(parseSignature({ ...d, text: ['hilbert(size: int; level: int; parity: int)'] }).params.length).toBe(3);
  });

  it('reads FOR loops from text', () => {
    const f = createElement('for', ['for i <- 1 to 10 by 2']) as For;
    expect(forInfo(f, DEFAULT_KEYWORDS)).toMatchObject({ style: 'COUNTER', var: 'i', start: '1', end: '10', step: 2 });
    const g = createElement('for', ['foreach v in {1, 2, 3}']) as For;
    expect(forInfo(g, DEFAULT_KEYWORDS)).toMatchObject({ style: 'TRAVERSAL', var: 'v', list: '{1, 2, 3}' });
  });
});

describe('expression translation', () => {
  it('maps operators per language', () => {
    expect(ex('a = b and not c', 'python')).toBe('a == b and not c');
    expect(ex('a = b and not c', 'java')).toBe('a == b && !c');
    expect(ex('a <> b or x mod 2 = 0', 'javascript')).toBe('a != b || x % 2 == 0');
    expect(ex('a div b', 'python')).toBe('a // b');
    expect(ex('true', 'python')).toBe('True');
    expect(ex('x + y', 'php')).toBe('$x + $y');
    expect(ex('sqrt(x)', 'java')).toBe('Math.sqrt(x)');
    expect(ex('length(s)', 'python')).toBe('len(s)');
    expect(ex('{1, 2, 3}', 'python')).toBe('[1, 2, 3]');
    expect(ex('{1, 2, 3}', 'java')).toBe('new int[]{1, 2, 3}');
    expect(ex("'abc'", 'java')).toBe('"abc"');
    expect(ex('"a<-b"', 'python')).toBe('"a<-b"');
  });
});

describe('code generation', () => {
  const d = fixture('all-elements.nsd');
  for (const l of LANGUAGES) {
    it(`generates ${l.name} for every element type`, () => {
      const r = generateCode(d, l.id);
      expect(r.code).toContain('Generated by Structorizer 3.32-35');
      expect(r.code.length).toBeGreaterThan(200);
      expect(r.lines.some((x) => x.ids.length > 0)).toBe(true);
      expect(r.fileName.endsWith('.' + l.ext)).toBe(true);
    });
  }

  it('produces sensible Python', () => {
    const code = generateCode(d, 'python').code;
    expect(code).toContain('if x > 0:');
    expect(code).toContain('for i in range(1, n + 1):');
    expect(code).toContain('for v in [1, 2, 3]:');
    expect(code).toContain('while n > 0:');
    expect(code).toContain('elif x in (2, 3):');
    expect(code).toContain('except Exception as ex:');
    expect(code).toContain('raise Exception("oops")');
    expect(code).toMatch(/# +while True:/); // disabled endless loop is commented out
  });

  it('produces Java with a class, declarations and a scanner', () => {
    const code = generateCode(d, 'java').code;
    expect(code).toContain('public class AllElements {');
    expect(code).toContain('public static void main(String[] args) {');
    expect(code).toContain('int n = 0;');
    expect(code).toContain('java.util.Scanner');
    expect(code).toContain('switch (x) {');
    expect(code).toContain('} while (!(n >= 3));');
  });

  it('generates subroutines as functions with a result', () => {
    let sub = createDiagram('sub');
    sub = { ...sub, text: ['fact(n: int): int'] };
    sub = insertAt(sub, { seq: { owner: 'root' }, index: 0 }, createElement('instruction', ['result <- 1']));
    const py = generateCode(sub, 'python').code;
    expect(py).toContain('def fact(n):');
    expect(py).toContain('return result');
    const java = generateCode(sub, 'java').code;
    expect(java).toContain('public static int fact(int n) {');
    const bash = generateCode(sub, 'bash').code;
    expect(bash).toContain('fact() {');
  });

  it('includes called subroutines from the pool', () => {
    let main = createDiagram('program');
    main = { ...main, text: ['Main'] };
    main = insertAt(main, { seq: { owner: 'root' }, index: 0 }, createElement('call', ['r <- twice(4)']));
    let sub = createDiagram('sub');
    sub = { ...sub, text: ['twice(x)'] };
    sub = insertAt(sub, { seq: { owner: 'root' }, index: 0 }, createElement('instruction', ['return 2 * x']));
    const js = generateCode(main, 'javascript', { pool: [main, sub] }).code;
    expect(js).toContain('function twice(x) {');
    expect(js).toContain('r = twice(4);');
  });
});
